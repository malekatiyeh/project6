
.ORIG x4000

ST R1, SAVE_R1
ST R2, SAVE_R2
ST R3, SAVE_R3
ST R7, SAVE_R7

GETC
OUT
LD R1, NEG_48
ADD R1, R0, R1

GETC
OUT
LD R2, NEG_48
ADD R2, R0, R2

ADD R3, R1, R1
ADD R1, R3, R3
ADD R1, R1, R1
ADD R1, R1, R3

ADD R0, R1, R2

LD R1, SAVE_R1
LD R2, SAVE_R2
LD R3, SAVE_R3
LD R7, SAVE_R7

RET

NEG_48 .FILL #-48
SAVE_R1 .BLKW 1
SAVE_R2 .BLKW 1
SAVE_R3 .BLKW 1
SAVE_R7 .BLKW 1

.END
