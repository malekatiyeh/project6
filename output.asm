
.ORIG x5000

ST R0, SAVE_R0
ST R1, SAVE_R1
ST R2, SAVE_R2
ST R7, SAVE_R7

ADD R1, R0, #0
AND R2, R2, #0

TEN_LOOP
ADD R1, R1, #-10
BRn TEN_DONE
ADD R2, R2, #1
BRnzp TEN_LOOP

TEN_DONE
ADD R1, R1, #10
ST R1, ONES

ADD R2, R2, #0
BRz PRINT_ONES

LD R0, ASCII_ZERO
ADD R0, R0, R2
OUT

PRINT_ONES
LD R0, ASCII_ZERO
LD R1, ONES
ADD R0, R0, R1
OUT

LD R0, SAVE_R0
LD R1, SAVE_R1
LD R2, SAVE_R2
LD R7, SAVE_R7

RET

ASCII_ZERO .FILL x0030
ONES .BLKW 1
SAVE_R0 .BLKW 1
SAVE_R1 .BLKW 1
SAVE_R2 .BLKW 1
SAVE_R7 .BLKW 1

.END
